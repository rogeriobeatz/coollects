async function setup(page:Parameters<typeof mockAcervo>[0],count=4){
 const state=await mockAcervo(page)
 state.items=Array.from({length:count},(_,index):ItemRow=>({...item,id:index===0?itemId:'00000000-0000-4000-8000-'+String(index+10).padStart(12,'0'),name:index===0?'Porsche 911 Carrera RS 2.7':'Miniatura '+index,brand:'Hot Wheels',photo_path:ownerId+'/photo-'+index+'.jpg',details:index===0?{color:'Amarelo',manufacturer:'Porsche',series:'Then and Now',scale:'1:64',seriesNumber:'9/10',collectionNumber:'208/250',year:2026,vehicleModel:'911 Carrera RS 2.7',vehicleYear:'1973',engine:'2.7 L, 6 cilindros',power:'210 cv',transmission:'Manual, 5 marchas'}:{manufacturer:'Ford',scale:'1:64'}}))
 state.links=state.items.map(row=>({collection_id:collectionId,item_id:row.id}))
 return state
}

