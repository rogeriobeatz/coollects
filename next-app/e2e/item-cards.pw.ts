test.describe('Toque no baralho',()=>{
 test.use({hasTouch:true,isMobile:true,viewport:{width:390,height:844}})
 test('Arrastar horizontalmente percorre cartas e arrastar verticalmente rola a página',async({page})=>{
  await setup(page,20)
  await page.goto('/colecao/'+collectionId)
  await page.getByRole('button',{name:'Baralho',exact:true}).click()
  const rail=page.locator('.item-deck-fan')
  await rail.scrollIntoViewIfNeeded()
  const session=await page.context().newCDPSession(page)
  async function drag(x:number,y:number,dx:number,dy:number){
   await session.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x,y}]})
   for(let step=1;step<=12;step++){
    await session.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:x+dx*step/12,y:y+dy*step/12}]})
    await page.waitForTimeout(16)
   }
   await session.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]})
  }
  const box=(await rail.boundingBox())!
  const y=Math.max(100,Math.min(600,box.y+150))
  await drag(300,y,-240,0)
  await expect.poll(()=>rail.evaluate(el=>el.scrollLeft)).toBeGreaterThan(100)
  await expect(page.locator('.cc-deck-controls')).toContainText('2 de 20')
  await expect(page.locator('.item-deck-entry')).toHaveCount(5)
  const transforms=await page.locator('.item-deck-entry .item-deck-layer').evaluateAll(elements=>elements.map(el=>getComputedStyle(el).transform))
  expect(new Set(transforms).size).toBeGreaterThan(1)
  await page.screenshot({path:'.next/artifacts/deck-depth-touch.png',animations:'disabled'})
  await drag(80,y,240,0)
  await expect(page.locator('.cc-deck-controls')).toContainText('1 de 20')
  const before=await page.evaluate(()=>scrollY)
  await drag(180,y,0,160)
  await expect.poll(()=>page.evaluate(()=>scrollY)).toBeLessThan(before)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page).toHaveURL(new RegExp('/colecao/'+collectionId))
  await rail.scrollIntoViewIfNeeded()
  const current=page.locator('.item-deck-hit[aria-current=true]')
  await current.tap()
  await expect(page).toHaveURL(/\/item\//)
  await expect(page.getByRole('dialog')).toHaveCount(0)
 })
})

